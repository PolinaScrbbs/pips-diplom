class Command(BaseCommand):
    help = "Загружает тестовые услуги: добавляет только недостающие по имени"

    def add_arguments(self, parser):
        parser.add_argument(
            "--force",
            action="store_true",
            help="Удалить все существующие услуги и загрузить заново",
        )

    def handle(self, *args, **options):
        force = options["force"]

        if force:
            Service.objects.all().delete()
            self.stdout.write("Все существующие услуги удалены.")

        # Все уже существующие имена в БД
        existing_names = set(Service.objects.values_list("name", flat=True))

        new_services = []
        for data in SERVICES:
            if data["name"] in existing_names:
                self.stdout.write(
                    f"Услуга '{data['name']}' уже есть в базе. Пропускаем."
                )
                continue

            # Добавляем только если нет по имени
            service = Service(
                name=data["name"],
                short_description=data["short_description"],
                description=data["description"],
                duration=data["duration"],
                price=data["price"],
            )
            new_services.append(service)

        if new_services:
            Service.objects.bulk_create(new_services, batch_size=10)
            self.stdout.write(
                self.style.SUCCESS(f"Добавлено {len(new_services)} новые услуги.")
            )
        else:
            self.stdout.write("Нет новых услуг для добавления.")

        total = Service.objects.count()
        self.stdout.write(f"Общее количество услуг в БД: {total}")

    help = "Загружает тестовые услуги (если ещё нет)"

    def add_arguments(self, parser):
        parser.add_argument(
            "--force",
            action="store_true",
            help="Удалить все существующие услуги и загрузить заново",
        )

    def handle(self, *args, **options):
        force = options["force"]

        if force:
            Service.objects.all().delete()
            self.stdout.write("Все существующие услуги удалены.")

        if Service.objects.exists() and not force:
            self.stdout.write("Услуги уже есть в базе. Загрузка не нужна.")
            return

        for data in SERVICES:
            service, created = Service.objects.get_or_create(
                name=data["name"],
                defaults={
                    "short_description": data["short_description"],
                    "description": data["description"],
                    "duration": data["duration"],
                    "price": data["price"],
                },
            )
            if created:
                self.stdout.write(f"Услуга '{service.name}' добавлена.")
            else:
                self.stdout.write(f"Услуга '{service.name}' уже была в базе.")

        self.stdout.write("Тестовый каталог услуг загружен.")

